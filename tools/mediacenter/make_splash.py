#!/usr/bin/env python3
# Turns docs/mmc_splash.png into tools/mediacenter/splash.h: the picture shown
# for 3 s when the player starts from the Scripts menu. 640x480 (4:3, as on
# the CRT), 256 colours, run-length coded: pairs of (count 1-255, colour).
# Needs Pillow; run it again after changing the picture.
import os
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', '..', 'docs', 'mmc_splash.png')
W, H = 640, 480
im = Image.open(src).convert('RGB').resize((W, H), Image.LANCZOS)
q = im.quantize(colors=256, method=Image.MEDIANCUT, dither=Image.NONE)
pal = q.getpalette()[:256 * 3]
pal += [0] * (256 * 3 - len(pal))
d = q.tobytes()
rle = bytearray()
i = 0
while i < len(d):
    j = i
    while j < len(d) and d[j] == d[i] and j - i < 255:
        j += 1
    rle += bytes((j - i, d[i]))
    i = j

with open(os.path.join(here, 'splash.h'), 'w') as f:
    f.write('// Generated by make_splash.py from docs/mmc_splash.png: do not edit.\n')
    f.write('#define SPLASH_W %d\n#define SPLASH_H %d\n' % (W, H))
    f.write('static const unsigned char splash_pal[768] = {\n')
    for k in range(0, 768, 24):
        f.write(','.join(str(v) for v in pal[k:k + 24]) + ',\n')
    f.write('};\nstatic const unsigned char splash_rle[%d] = {\n' % len(rle))
    for k in range(0, len(rle), 32):
        f.write(','.join(str(v) for v in rle[k:k + 32]) + ',\n')
    f.write('};\n')
