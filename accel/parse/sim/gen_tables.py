#!/usr/bin/env python3
# Makes the CABAC tables for the model (cab_tables.h) and the RTL (../rtl/*.hex)
# from FFmpeg's sources: context init (m, n) for I and P/B idc 0-2, and the
# engine tables printed by tabs (rangeTabLPS, transIdx, last 8x8 offsets).
# Usage: gen_tables.py <ffmpeg src> <tabs output>
import re, sys
src = open(sys.argv[1] + '/libavcodec/h264_cabac.c').read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
src = re.sub(r'//[^\n]*', '', src)
def table(name):
    i = src.index(name)
    body = src[src.index('=', i):src.index('};', i)]
    v = [int(x) for x in re.findall(r'-?\d+', body)]
    return v
I = table('cabac_context_init_I[1024][2]')
PB = table('cabac_context_init_PB[3][1024][2]')
assert len(I) == 2048 and len(PB) == 6144
sets = [I, PB[0:2048], PB[2048:4096], PB[4096:6144]]
t = {}
for line in open(sys.argv[2]):
    f = line.split(); t[f[0]] = [int(x) for x in f[1:]]
sig8 = [0, 1, 2, 3, 4, 5, 5, 4, 4, 3, 3, 4, 4, 4, 5, 5, 4, 4, 4, 4, 3, 3, 6, 7, 7, 7, 8, 9,10, 9, 8, 7,
        7, 6,11,12,13,11, 6, 7, 8, 9,14,10, 9, 8, 6,11, 12,13,11, 6, 9,14,10, 9,11,12,13,11,14,10,12]
assert len(sig8) == 63
last8 = t['LAST8'][:63]
with open('cab_tables.h', 'w') as o:
    o.write('// Generated by gen_tables.py: do not edit.\n')
    o.write('static const signed char cab_init[4][1024][2] = {\n')
    for s in sets:
        o.write(' {' + ','.join('{%d,%d}' % (s[2*i], s[2*i+1]) for i in range(1024)) + '},\n')
    o.write('};\n')
    o.write('static const unsigned char cab_rlps[64][4] = {' + ','.join('{%s}' % ','.join(map(str, t['RLPS'][4*p:4*p+4])) for p in range(64)) + '};\n')
    o.write('static const unsigned char cab_tmps[64] = {%s};\n' % ','.join(map(str, t['TMPS'])))
    o.write('static const unsigned char cab_tlps[64] = {%s};\n' % ','.join(map(str, t['TLPS'])))
    o.write('static const unsigned char cab_sig8[63] = {%s};\n' % ','.join(map(str, sig8)))
    o.write('static const unsigned char cab_last8[63] = {%s};\n' % ','.join(map(str, last8)))
# RTL: init ROM, 4096 words of 16 bits: m (signed 8) << 8 | n (signed 8); address set * 1024 + ctx
with open('../rtl/cab_init.hex', 'w') as o:
    for s in sets:
        for i in range(1024):
            o.write('%04x\n' % (((s[2*i] & 0xFF) << 8) | (s[2*i+1] & 0xFF)))
# rangeTabLPS ROM: 256 words of 8 bits, address p * 4 + q
with open('../rtl/cab_rlps.hex', 'w') as o:
    for v in t['RLPS']:
        o.write('%02x\n' % v)
# transIdxLPS ROM: 64 words of 6 bits
with open('../rtl/cab_tlps.hex', 'w') as o:
    for v in t['TLPS']:
        o.write('%02x\n' % v)
print('ok', len(sets), 'init sets')
